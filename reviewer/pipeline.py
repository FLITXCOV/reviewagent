"""Review pipeline. Modes: 'baseline' | 'multicat' | 'multinode'. Retrieval: 'none' | 'symbol'."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

from reviewer.diffparse import (Hunk, changed_new_spans, parse_unified_diff, render_hunk,
                                reviewable_files, split_hunk)
from reviewer.llm import LLMClient, LLMOutputError, LLMUnavailable
from reviewer.schemas import CATEGORIES, Finding, JudgeVerdict, ReviewOutput, coerce_findings
from reviewer.symbols import Symbol, SymbolIndex

PROMPT_VERSION = "v2"
SEV_RANK = {"low": 0, "medium": 1, "high": 2}

SYSTEM = """You are a meticulous senior code reviewer. You review a code CHANGE (a diff), not the whole repository.
Rules:
- Report only concrete defects that you can point to in the shown code. Never report style, naming, formatting, type-annotation or refactoring suggestions.
- If the change looks correct, return {"findings": []}. Returning no findings is valid and often correct.
- Line numbers refer to the NEW file: use the number in the left column. A line marked '-' was removed and has no number; if the defect is the REMOVAL of code, cite the nearest numbered line at the removal point.
- Output ONLY a JSON object: {"findings":[{"file":str,"line_start":int,"line_end":int,"category":str,"severity":str,"confidence":number,"message":str,"evidence":[str],"suggested_fix":str|null}]}
- category is one of: security, error_handling, tests, logic. severity is one of: low, medium, high. confidence is between 0 and 1.
- message must state the concrete failing scenario: which input or state breaks, and what goes wrong."""

FOCUS = {
    "logic": "Focus ONLY on logic errors: wrong conditions, wrong values, off-by-one, wrong operators, removed or altered behaviour that other code relies on, mishandled edge cases.",
    "security": "Focus ONLY on security: injection, unsafe deserialization, path traversal, hardcoded secrets, missing authorization or validation of untrusted input.",
    "error_handling": "Focus ONLY on error handling: unchecked failures, swallowed or bare exceptions, missing input validation, missing None/empty checks, resource leaks.",
    "tests": "Focus ONLY on tests: changed behaviour that has no test coverage, or tests that no longer assert the behaviour.",
}
ALL_FOCUS = "Check for ALL of: logic errors, error handling, security problems, and missing test coverage."

SUMMARY_SYSTEM = "You summarise code changes. Reply with 2-3 plain sentences stating what the change is trying to do. No JSON."

JUDGE_SYSTEM = """You verify whether a code-review FINDING identifies the SAME root cause as a known, real bug fix.
You receive:
1. The real fix patch (which fixed the defect in production).
2. A code review finding (which was generated by inspecting the buggy code).

DIRECTION RULE:
- The finding describes what is BROKEN or MISSING in the buggy code (e.g. "missing check", "removed handling", "wrong order").
- The patch shows how it was FIXED in production.
- If the finding points out the defect that the patch resolves (e.g. finding says "X was removed or behaves incorrectly", and the patch adds or restores X), answer true.
- If the finding merely mentions the same function/lines, gives generic advice, or describes an unrelated problem, answer false.

Output ONLY JSON: {"matches_root_cause": true|false, "reasoning": "one sentence explaining why it matches or differs"}"""


def batch_hunks(pieces: Sequence[Hunk], max_chars: int = 24000) -> list[list[Hunk]]:
    batches: list[list[Hunk]] = []
    cur: list[Hunk] = []
    size = 0
    for h in pieces:
        n = len(render_hunk(h))
        if cur and size + n > max_chars:
            batches.append(cur)
            cur, size = [], 0
        cur.append(h)
        size += n
    if cur:
        batches.append(cur)
    return batches


def render_context(symbols: Sequence[Symbol]) -> str:
    if not symbols:
        return ""
    parts = ["## Related code from the repository (read-only context, NOT part of the change)"]
    for s in symbols:
        parts.append(f"### {s.qualname}  ({s.file}:{s.start}-{s.end}{', test' if s.is_test else ''})\n{s.code}")
    return "\n\n".join(parts)


def dedupe_and_rank(findings: Sequence[Finding], min_conf: float = 0.5, max_findings: int = 10) -> list[Finding]:
    kept: list[Finding] = []
    for f in sorted((f for f in findings if f.confidence >= min_conf),
                    key=lambda f: (-f.confidence, f.file, f.line_start, f.category)):
        dup = any(k.file == f.file and k.category == f.category and
                  f.line_start <= k.line_end + 3 and f.line_end >= k.line_start - 3 for k in kept)
        if not dup:
            kept.append(f)
    kept.sort(key=lambda f: (-SEV_RANK[f.severity], -f.confidence, f.file, f.line_start))
    return kept[:max_findings]


def run_review(diff_text: str, client: LLMClient, *, mode: str = "multinode", retrieval: str = "none",
               repo_root: str | None = None, min_conf: float = 0.5, max_findings: int = 10,
               max_batch_chars: int = 24000, max_context_symbols: int = 8) -> ReviewOutput:
    if mode not in {"baseline", "multicat", "multinode"} or retrieval not in {"none", "symbol"}:
        raise ValueError("bad mode or retrieval")
    out = ReviewOutput()
    calls0, retries0, repairs0 = client.network_calls + client.cache_hits, client.retries, client.json_repairs

    files = reviewable_files(parse_unified_diff(diff_text))
    pieces: list[Hunk] = []
    for fd in files:
        for h in fd.hunks:
            parts = split_hunk(h)
            out.hunk_splits += len(parts) - 1
            pieces.extend(parts)
    if not pieces:
        return out
    batches = batch_hunks(pieces, max_batch_chars)

    context = ""
    if retrieval == "symbol" and mode != "baseline" and repo_root:
        index = SymbolIndex(repo_root)
        chosen: list[Symbol] = []
        seen: set[str] = set()
        for fd in files:
            for start, _end in changed_new_spans(fd):
                for s in index.retrieve(fd.path, start):
                    if s.sid not in seen and len(chosen) < max_context_symbols:
                        seen.add(s.sid)
                        chosen.append(s)
        context = render_context(chosen)

    def ask(system_focus: str, batch: list[Hunk], summary: str, name: str) -> list[Finding]:
        user = (f"{system_focus}\n\n" + (f"Change summary: {summary}\n\n" if summary else "") +
                "## The change under review\n" + "\n\n".join(render_hunk(h) for h in batch) +
                (("\n\n" + context) if context else ""))
        try:
            data = client.complete_json(SYSTEM, user, version=PROMPT_VERSION)
            raw = data.get("findings", []) if isinstance(data, dict) else data
            found, dropped = coerce_findings(raw)
            out.dropped_findings += dropped
            return found
        except (LLMUnavailable, LLMOutputError):
            out.failed_nodes.append(name)
            return []

    findings: list[Finding] = []
    if mode == "baseline":
        for i, b in enumerate(batches):
            findings += ask("Review this change.", b, "", f"baseline[{i}]")
    elif mode == "multicat":
        for i, b in enumerate(batches):
            findings += ask(ALL_FOCUS, b, "", f"multicat[{i}]")
    else:
        summary = ""
        try:
            first = "\n\n".join(render_hunk(h) for h in batches[0])[:6000]
            summary = client.complete(SUMMARY_SYSTEM, first, version=PROMPT_VERSION).strip()
        except LLMUnavailable:
            out.failed_nodes.append("summary")
        out.summary = summary
        for i, b in enumerate(batches):
            for cat in CATEGORIES:
                findings += ask(FOCUS[cat], b, summary, f"{cat}[{i}]")

    out.findings = dedupe_and_rank(findings, min_conf, max_findings)
    out.llm_calls = client.network_calls + client.cache_hits - calls0
    out.retries = (client.retries - retries0) + (client.json_repairs - repairs0)
    return out


class Judge:
    """Cross-model judge. Use a DIFFERENT model family than the reviewer. Never raises; counts errors."""
    def __init__(self, client: LLMClient):
        self.client, self.errors = client, 0

    def __call__(self, finding: Finding, fix_patch: str) -> JudgeVerdict:
        user = (f"## Real fix patch\n{fix_patch[:8000]}\n\n## Finding\nfile: {finding.file} "
                f"lines {finding.line_start}-{finding.line_end}\ncategory: {finding.category}\n"
                f"message: {finding.message}")
        try:
            d = self.client.complete_json(JUDGE_SYSTEM, user, version=PROMPT_VERSION)
            return JudgeVerdict(matches_root_cause=bool(d.get("matches_root_cause")), reasoning=str(d.get("reasoning", "")))
        except Exception as e:  # judge failure must not crash the eval; it is counted and reported
            self.errors += 1
            return JudgeVerdict(matches_root_cause=False, reasoning=f"judge_error: {e}")
