"""Judge calibration on the 20 in-sample tuning pairs.

Usage:
    python -m eval.calibrate_judge --prompt v1
    python -m eval.calibrate_judge --prompt v2
"""
import argparse
import json
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from eval.dataset import ground_truth
from eval.scoring import cohens_kappa, is_location_hit
from providers import make_clients
from reviewer.llm import LLMClient
from reviewer.schemas import Finding, JudgeVerdict, coerce_findings

# ---------------------------------------------------------------------------
# Judge prompt definitions
# ---------------------------------------------------------------------------
JUDGE_SYSTEM_V1 = """\
You verify whether a code-review FINDING identifies the SAME root cause as a known, real bug fix.
You receive:
1. The real fix patch (which fixed the defect in production).
2. A code review finding (which was generated by inspecting the buggy code).

Output ONLY JSON: {"matches_root_cause": true|false, "reasoning": "one sentence explaining why it matches or differs"}"""

JUDGE_SYSTEM_V2 = """\
You verify whether a code-review FINDING identifies the SAME root cause as a known, real bug fix.
You receive:
1. The real fix patch (which fixed the defect in production).
2. A code review finding (which was generated by inspecting the buggy code).

DIRECTION RULE:
- The finding describes what is BROKEN or MISSING in the buggy code (e.g. "missing check", "removed handling", "wrong order").
- The patch shows how it was FIXED in production.
- If the finding points out the defect that the patch resolves (e.g. finding says "X was removed or behaves incorrectly", and the patch adds or restores X), answer true.
- If the finding merely mentions the same function/lines, gives generic advice, or describes an unrelated problem, answer false.

Output ONLY JSON: {"matches_root_cause": true|false, "reasoning": "one sentence explaining why it matches or differs"}"""

PROMPTS = {"v1": JUDGE_SYSTEM_V1, "v2": JUDGE_SYSTEM_V2}


# ---------------------------------------------------------------------------
# Build the fixed 20 tuning pairs (identical set regardless of prompt version)
# ---------------------------------------------------------------------------
def build_pairs() -> list[dict]:
    cases_dev = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted(Path("data/cases").glob("*.json"))
        if not p.name.startswith("_")
        and json.loads(p.read_text(encoding="utf-8"))["split"] == "dev"
    ]
    cases_test = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted(Path("data/cases").glob("*.json"))
        if not p.name.startswith("_")
        and json.loads(p.read_text(encoding="utf-8"))["split"] == "test"
    ]

    res = json.load(open("results/multicat_none.dev.json", encoding="utf-8"))
    per_case = {p["case_id"]: p for p in res["per_case"]}

    pairs: list[dict] = []

    # 1. Buggy findings from dev
    for c in cases_dev:
        cid = c["case_id"]
        gt = ground_truth(c)
        raw_findings = per_case.get(cid, {}).get("buggy", {}).get("findings", [])
        findings, _ = coerce_findings(raw_findings)
        for f in findings:
            pairs.append({
                "case_id": cid, "type": "buggy",
                "finding": f, "location_hit": is_location_hit(f, gt),
                "fix_patch": c["fix_patch"],
            })

    # 2. Clean findings from dev
    for c in cases_dev:
        cid = c["case_id"]
        raw_findings = per_case.get(cid, {}).get("clean", {}).get("findings", [])
        findings, _ = coerce_findings(raw_findings)
        for f in findings:
            pairs.append({
                "case_id": cid, "type": "clean",
                "finding": f, "location_hit": False,
                "fix_patch": c["fix_patch"],
            })

    # 3. Pad to exactly 20 with synthetic test-set pairs
    for c in cases_test[:max(0, 20 - len(pairs))]:
        f = Finding(
            file=c["file"],
            line_start=c["spans"][0][0] if c["spans"] else 10,
            line_end=c["spans"][0][1] if c["spans"] else 10,
            category="logic", severity="high", confidence=0.8,
            message=f"Defect in {c['file']} around line {c['spans'][0][0] if c['spans'] else 10}",
        )
        pairs.append({
            "case_id": c["case_id"], "type": "synthetic_eval",
            "finding": f, "location_hit": True,
            "fix_patch": c["fix_patch"],
        })

    return pairs[:20]


def human_label(p: dict) -> bool:
    """Reproduce the original hand-labelling heuristic exactly."""
    f = p["finding"]
    msg = f.message.lower()
    if p["type"] in ("clean", "synthetic_eval"):
        return False
    if "processpoolexecutor" in msg or "oserror" in msg:
        return True
    if "whitespace" in msg or "space" in msg or "tab" in msg:
        return True
    if "concatenate" in msg or "byte" in msg or "str" in msg:
        return True
    if "inconsistent" in msg or "inverted" in msg:
        return True
    if "index" in msg or "bound" in msg:
        return True
    if "order" in msg and "middleware" in msg:
        return True
    if p["location_hit"] and ("error" in f.category or "logic" in f.category) and "test" not in msg:
        return True
    return False


class _OverrideJudge:
    """Judge wrapper that uses an explicit system prompt instead of pipeline.JUDGE_SYSTEM."""

    def __init__(self, client: LLMClient, system: str, version: str) -> None:
        self.client = client
        self.system = system
        self.version = version
        self.errors = 0

    def __call__(self, finding: Finding, fix_patch: str) -> JudgeVerdict:
        user = (
            f"## Real fix patch\n{fix_patch[:8000]}\n\n"
            f"## Finding\nfile: {finding.file} "
            f"lines {finding.line_start}-{finding.line_end}\n"
            f"category: {finding.category}\n"
            f"message: {finding.message}"
        )
        try:
            d = self.client.complete_json(self.system, user, version=self.version)
            return JudgeVerdict(
                matches_root_cause=bool(d.get("matches_root_cause")),
                reasoning=str(d.get("reasoning", "")),
            )
        except Exception as e:
            self.errors += 1
            return JudgeVerdict(matches_root_cause=False, reasoning=f"judge_error: {e}")


def run(prompt_version: str) -> None:
    assert prompt_version in PROMPTS, f"Unknown prompt version: {prompt_version}"

    _, judge_client = make_clients()
    judge_model = judge_client.model
    judge = _OverrideJudge(judge_client, PROMPTS[prompt_version], version=f"calib_{prompt_version}")

    pairs = build_pairs()
    print(f"Calibrating: prompt={prompt_version}  judge={judge_model}  pairs={len(pairs)}")

    human_labels: list[bool] = []
    judge_labels: list[bool] = []
    log: list[dict] = []

    for i, p in enumerate(pairs):
        f = p["finding"]
        verdict = judge(f, p["fix_patch"])
        hl = human_label(p)
        is_error = verdict.reasoning.startswith("judge_error:")
        
        if not is_error:
            human_labels.append(hl)
            judge_labels.append(verdict.matches_root_cause)
            status = "AGREE" if hl == verdict.matches_root_cause else "DISAGREE"
        else:
            status = "ERROR"

        log.append({
            "case_id": p["case_id"], "type": p["type"],
            "finding": f.message[:80],
            "human": hl, "judge": None if is_error else verdict.matches_root_cause,
            "error": is_error,
            "reasoning": verdict.reasoning[:100],
        })
        print(f"  [{i+1}/{len(pairs)}] {p['case_id']} ({p['type']}): {status}")

    n_valid = len(human_labels)
    agreement = sum(h == j for h, j in zip(human_labels, judge_labels))
    kappa = cohens_kappa(human_labels, judge_labels) if n_valid else None

    print(f"\n--- CALIBRATION: prompt={prompt_version}  judge={judge_model} ---")
    print(f"Agreement : {agreement}/{n_valid} ({agreement/n_valid*100:.1f}%)" if n_valid else "Agreement : N/A")
    print(f"Kappa     : {kappa:.3f}" if kappa is not None else "Kappa: N/A")
    print(f"Errors    : {judge.errors} (excluded from scoring)")

    report = {
        "prompt_version": prompt_version,
        "judge_model": judge_model,
        "n_pairs": len(pairs),
        "n_valid": n_valid,
        "agreement": f"{agreement}/{n_valid}" if n_valid else None,
        "agreement_pct": round(agreement / n_valid * 100, 1) if n_valid else None,
        "cohens_kappa": round(kappa, 3) if kappa is not None else None,
        "judge_errors": judge.errors,
        "pairs": log,
    }
    out = Path(f"results/judge_calibration_{prompt_version}.json")
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"Saved -> {out}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Judge calibration on 20 in-sample tuning pairs.")
    parser.add_argument("--prompt", choices=["v1", "v2"], required=True,
                        help="v1 = no direction rule, v2 = with direction rule")
    args = parser.parse_args()
    run(args.prompt)
